// Generates tiny blurred base64 placeholders for the app's "hero" raster images
// and writes them to a typed map consumed by getBlurProps() (see
// src/core-ui/data/blur-placeholders.generated.ts).
//
// next/image needs a `blurDataURL` to render `placeholder="blur"` when the
// image is referenced by a runtime string src (not a static import). Rather
// than hand-maintain those blobs, this script derives them from the files in
// public/ so they never drift. Re-run after adding/changing a hero image:
//
//   pnpm --filter web gen:blur
//
// Each blob is a ~16px WebP (a few hundred bytes) inlined as a data URI.
import { createRequire } from 'node:module';
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// sharp lives in the pnpm store (a transitive dep of next), not hoisted into
// apps/web/node_modules — resolve it from the monorepo root store.
const require = createRequire(import.meta.url);
const sharp = require(
  path.join(WEB, '../../node_modules/.pnpm/sharp@0.34.5/node_modules/sharp'),
);

const PUBLIC = path.join(WEB, 'public');
const OUT = path.join(WEB, 'src/core-ui/data/blur-placeholders.generated.ts');

// Directories whose raster images should get a placeholder, plus loose files.
// Everything here is served through next/image at a visible size, where the
// blur-up matters; tiny 18px chrome icons are skipped (they load instantly).
const DIRS = ['icons/achievements', 'world'];
const GLOBAL_FILES = [
  'shiny_chest.webp',
  'shiny_chest_open.webp',
  'chest.webp',
  'tier-01-seed.webp',
  'tier-02-sprout.webp',
  'tier-03-seedling.webp',
  'gold_medal.webp',
  'silver_medal.webp',
  'bronze_medal.webp',
  'coin.png',
].map((f) => path.join('icons/global', f));

const isRaster = (f) => /\.(png|jpe?g|webp)$/i.test(f);

const collect = async () => {
  const rel = [...GLOBAL_FILES];
  for (const dir of DIRS) {
    const entries = await readdir(path.join(PUBLIC, dir));
    for (const e of entries) if (isRaster(e)) rel.push(path.join(dir, e));
  }
  return rel;
};

const toBlur = async (relPath) => {
  const buf = await sharp(path.join(PUBLIC, relPath))
    .resize(16, 16, { fit: 'inside' })
    .webp({ quality: 40 })
    .toBuffer();
  return `data:image/webp;base64,${buf.toString('base64')}`;
};

const files = (await collect()).sort();
const entries = [];
for (const rel of files) {
  const key = '/' + rel.split(path.sep).join('/');
  entries.push([key, await toBlur(rel)]);
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-blur-placeholders.mjs — do not edit by hand.
// Run \`pnpm --filter web gen:blur\` to refresh. Tiny base64 blur-up previews
// keyed by public path, consumed via getBlurProps().
const BLUR: Record<string, string> = {
${body}
};

/**
 * Spread onto a next/image <Image> to get an instant blur-up placeholder:
 *   <Image src={src} {...getBlurProps(src)} ... />
 * Returns nothing for unknown srcs (e.g. remote badge URLs), so the image just
 * renders without a placeholder instead of erroring.
 */
export const getBlurProps = (
  src: string,
): { placeholder: 'blur'; blurDataURL: string } | Record<string, never> => {
  const blurDataURL = BLUR[src];
  return blurDataURL ? { placeholder: 'blur', blurDataURL } : {};
};
`;

await writeFile(OUT, out);
console.log(`Wrote ${entries.length} blur placeholders to ${path.relative(WEB, OUT)}`);
